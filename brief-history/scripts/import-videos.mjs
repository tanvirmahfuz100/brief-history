import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const guidePath = [
  path.resolve(root, '..', 'sources', 'ais_bba_youtube_course_guide.md'),
  path.resolve(root, '..', 'ais_bba_youtube_course_guide.md'),
].find((candidate) => fs.existsSync(candidate));
const outPath = path.resolve(root, 'src', 'data', 'videos.generated.ts');
const check = process.argv.includes('--check');

if (!fs.existsSync(guidePath)) {
  console.error(`Video guide not found: ${guidePath}`);
  process.exit(1);
}

const lines = fs.readFileSync(guidePath, 'utf8').split(/\r?\n/);
const courses = new Map();
let current = null;
let section = '';
let topic = 'Video lessons';
let coverageLines = [];
let collectingCoverage = false;

const linkPattern = /\[([^\]]+)\]\((https:\/\/www\.youtube\.com\/watch\?v=[^)\s]+)\)/g;

function stripMarkdown(text) {
  return text
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/\*([^*]+)\*/g, '$1')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();
}

function getCourse(code, title) {
  if (!courses.has(code)) {
    courses.set(code, {
      code: `ais ${code}`,
      guideTitle: title.replace(/^[—–-]\s*/, '').trim(),
      topics: [],
      coverage: '',
      videoCount: 0,
    });
  }
  return courses.get(code);
}

function addVideo(course, title, url, rest, topicName) {
  if (course.topics.some((t) => t.videos.some((v) => v.url === url))) return;

  const cleanedRest = rest
    .trim()
    .replace(/^\*\*\s*/, '')
    .replace(/^[—–-]\s*/, '')
    .replace(/^[,;:]\s*/, '')
    .trim();

  let channel = '';
  let note = cleanedRest;
  const channelMatch = cleanedRest.match(/^\*\*([^*]+)\*\*\s*[—–-]?\s*(.*)$/);
  if (channelMatch) {
    channel = stripMarkdown(channelMatch[1]);
    note = channelMatch[2];
  }

  note = stripMarkdown(note)
    .replace(/^[.,;:—–-]+\s*/, '')
    .replace(/\*\*Exam use:\*\*/g, 'Exam use:')
    .replace(/\*\*Coverage:\*\*/g, 'Coverage:');
  if (note.length > 600) note = `${note.slice(0, 597).trimEnd()}…`;

  let group = course.topics.find((t) => t.title === topicName);
  if (!group) {
    group = { title: topicName, videos: [] };
    course.topics.push(group);
  }
  group.videos.push({
    title: stripMarkdown(title).replace(/^\*+|\*+$/g, '').trim(),
    url,
    channel,
    note,
  });
  course.videoCount += 1;
}

for (const line of lines) {
  const courseMatch = line.match(/^# (\d{4})\b\s*(.*)$/);
  if (courseMatch) {
    current = getCourse(courseMatch[1], courseMatch[2]);
    section = '';
    topic = 'Video lessons';
    collectingCoverage = false;
    coverageLines = [];
    continue;
  }
  if (!current) continue;

  const sectionMatch = line.match(/^##\s+(.+)$/);
  if (sectionMatch) {
    section = sectionMatch[1].trim();
    topic = 'Video lessons';
    if (/^coverage audit/i.test(section)) {
      collectingCoverage = true;
      coverageLines = [];
    } else if (collectingCoverage) {
      current.coverage = current.coverage || stripMarkdown(coverageLines.join(' '));
      collectingCoverage = false;
    }
    continue;
  }

  if (/^#\s+/.test(line)) {
    if (collectingCoverage) {
      current.coverage = current.coverage || stripMarkdown(coverageLines.join(' '));
      collectingCoverage = false;
    }
    continue;
  }

  if (collectingCoverage) {
    if (line.trim() && !/^##\s+/.test(line)) coverageLines.push(line);
    continue;
  }

  if (!/^topic-to-video map/i.test(section)) continue;

  const topicMatch = line.match(/^###\s+(.+)$/);
  if (topicMatch) {
    const heading = stripMarkdown(topicMatch[1]);
    if (!/not covered|coverage/i.test(heading)) topic = heading;
    continue;
  }

  let match;
  linkPattern.lastIndex = 0;
  while ((match = linkPattern.exec(line)) !== null) {
    const url = match[2];
    const rest = line.slice(match.index + match[0].length);
    addVideo(current, match[1], url, rest, topic);
  }
}

for (const course of courses.values()) {
  if (collectingCoverage) course.coverage = course.coverage || stripMarkdown(coverageLines.join(' '));
  if (!course.videoCount) {
    console.error(`No videos parsed for ${course.code}`);
    process.exitCode = 1;
  }
}

const list = [...courses.values()].sort((a, b) => a.code.localeCompare(b.code));
if (list.length !== 45) {
  console.error(`Expected 45 course entries, found ${list.length}`);
  process.exitCode = 1;
}

const output = `// Generated by scripts/import-videos.mjs from ais_bba_youtube_course_guide.md.\n// Do not edit by hand. Run \`npm run import:videos\` to refresh.\n\nexport interface VideoLink {\n  title: string;\n  url: string;\n  channel: string;\n  note: string;\n}\n\nexport interface VideoTopic {\n  title: string;\n  videos: VideoLink[];\n}\n\nexport interface VideoCourse {\n  code: string;\n  guideTitle: string;\n  topics: VideoTopic[];\n  coverage: string;\n  videoCount: number;\n}\n\nexport const VIDEO_COURSES: VideoCourse[] = ${JSON.stringify(list, null, 2)};\n\nexport const VIDEO_BY_CODE = new Map(VIDEO_COURSES.map((course) => [course.code, course]));\n`;

if (check) {
  const existing = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
  if (existing !== output) {
    console.error('src/data/videos.generated.ts is out of date. Run npm run import:videos.');
    process.exitCode = 1;
  } else {
    console.log(`Video data is up to date (${list.length} courses, ${list.reduce((n, c) => n + c.videoCount, 0)} videos).`);
  }
} else {
  fs.writeFileSync(outPath, output);
  console.log(`Wrote ${path.relative(root, outPath)} (${list.length} courses, ${list.reduce((n, c) => n + c.videoCount, 0)} videos).`);
}
